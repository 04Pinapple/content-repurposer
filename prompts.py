PLATFORMS = {
    "xiaohongshu": {
        "label": "小红书",
        "goal": "让人愿意点开、读完、收藏",
        "rules": [
            "标题 20 字以内，给具体利益点或反差，不做夸张标题党",
            "正文 300-600 字，每段 1-3 行，段与段之间空一行",
            "第一句话直接给结论或场景，不要铺垫背景",
            "结尾一句引导互动（提问、征集经验），不要硬要点赞关注",
            "末尾给 3-6 个话题标签，用 # 开头",
        ],
    },
    "wechat": {
        "label": "微信公众号",
        "goal": "把一个观点讲透，让人读完有收获",
        "rules": [
            "标题 24 字以内，可以用主标题 + 副标题的形式",
            "正文 800-1500 字，用二级小标题分 3-5 个部分",
            "开头 100 字内点明读者会遇到的问题",
            "每个观点后面跟一个具体例子或数据，避免空泛结论",
            "结尾给一句可以带走的话，再加一句行动建议",
        ],
    },
    "weibo": {
        "label": "微博",
        "goal": "在信息流里被读完并转发",
        "rules": [
            "正文 140 字以内（不含话题），一句话一个意思",
            "第一句就是最有信息量或最有反差的那句",
            "可用 1-2 个 emoji，不超过 2 个",
            "末尾带 1-2 个话题标签",
            "保留判断和立场，不要写成中立的资讯播报",
        ],
    },
    "script": {
        "label": "短视频口播",
        "goal": "前 3 秒留住人，完整听完",
        "rules": [
            "开头 3 秒给钩子：一个反常识结论、一个具体数字或一个提问",
            "全篇口语化，句子短，避免书面连接词",
            "总时长控制在 60-90 秒（约 250-350 字）",
            "中间每 15 秒左右给一个新信息点，防止跳出",
            "结尾给一个明确的行动指令",
            "用分镜形式输出：镜号 / 口播文案 / 画面提示",
        ],
    },
}

DEFAULT_PLATFORMS = ["xiaohongshu", "wechat", "weibo", "script"]


def build_prompt(platform: str, article: str, tone: str, brand: str = "") -> str:
    spec = PLATFORMS[platform]
    rules = "\n".join(f"- {rule}" for rule in spec["rules"])
    brand_line = f"\n账号人设 / 语气要求：{brand.strip()}" if brand.strip() else ""

    return f"""你是一位做过多年的内容编辑，熟悉不同平台的阅读习惯。

## 原始素材
{article}

## 任务
把上面的素材改写成【{spec['label']}】版本。这一版的目标是：{spec['goal']}。

## 平台规范
{rules}

## 语气
{tone}{brand_line}

## 硬性要求
- 只能使用素材里出现过的事实、数字和观点，不要虚构经历、数据或引用
- 素材里的信息不足以支撑某个段落时，就少写一点，不要凑字数
- 不要出现"以下是""希望对你有帮助"这类套话
- 直接输出成稿，不要解释你的改写思路
"""
